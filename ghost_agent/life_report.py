"""Life layer run report: what the assistant lane did over a window (default 24 h).

Everything comes from Ghost's own durable records (heartbeat receipts, Telegram
receipts, assistant receipts, the overnight log, situation history, the
supervisor health file). Nothing is estimated.
"""
from __future__ import annotations

import json
import time
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any, Optional

from . import heartbeat, situation
from .runtime import EventBus


def _jsonl(path: Path, since: float, stamp) -> list[dict[str, Any]]:
    out = []
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            try:
                row = json.loads(line)
            except ValueError:
                continue
            if stamp(row) >= since:
                out.append(row)
    return out


def _json_dir(folder: Path, since: float, key: str) -> list[dict[str, Any]]:
    out = []
    for path in folder.glob("*.json"):
        try:
            row = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(row, dict) and float(row.get(key, 0) or 0) >= since:
            out.append(row)
    return out


def build(root: Path, hours: float = 24.0, now: Optional[float] = None) -> dict[str, Any]:
    """Collect the counts for one window ending at `now`."""
    root = Path(root).resolve()
    now = time.time() if now is None else now
    since = now - hours * 3600
    receipts = [r for r in heartbeat.receipts(root, 100_000) if r.get("at", 0) >= since]
    beats = [r for r in receipts if not r.get("prompted")]
    messages = [r for r in receipts if r.get("action") == "message_owner" and r.get("status") == "done"]
    telegram_sent = [r for r in messages if (r.get("delivery") or {}).get("status") == "sent"]
    oj = root / ".ghost" / "openjarvis"
    chats = _json_dir(oj / "receipts", since, "started_at")
    inbound = _json_dir(oj / "telegram-receipts", since, "received_at")
    overnight = _jsonl(root / ".ghost" / "overnight" / "log.jsonl", since,
                       lambda r: datetime.fromisoformat(r.get("ts", "1970-01-01T00:00:00")).timestamp())
    ticks = Counter(r.get("proactive", "") for r in overnight)
    samples = situation.history(root, since)
    freshness = {}
    for name in situation.FIELDS:
        known = sum(1 for s in samples if (s["f"].get(name) or ["unknown"])[0] != "unknown")
        freshness[name] = round(known / len(samples), 3) if samples else None
    events = EventBus(root).recent(100_000)
    stops = [e for e in events if e.created_at >= since and e.kind in {"emergency_stop", "owner.contact"}]
    supervisor = {}
    try:
        supervisor = json.loads((root / ".ghost" / "life-logs" / "supervisor.json").read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        pass
    model_calls = {
        "heartbeat": sum(1 for r in beats if r.get("model_called")),
        "proactive_ticks": sum(n for status, n in ticks.items() if status not in {"", "stopped", "deferred"}),
        "telegram_chat": len(chats),
        "briefings": sum(1 for e in events if e.created_at >= since and e.kind == "owner.briefing"),
    }
    return {
        "window": {"from": datetime.fromtimestamp(since).isoformat(timespec="minutes"),
                   "to": datetime.fromtimestamp(now).isoformat(timespec="minutes"), "hours": hours},
        "heartbeats": {"total": len(beats), "actions": dict(Counter(f"{r.get('action')}:{r.get('status')}" for r in beats))},
        "messages": {"total": len(messages), "unprompted": sum(1 for r in messages if not r.get("prompted")),
                     "prompted": sum(1 for r in messages if r.get("prompted")),
                     "telegram_sent": len(telegram_sent),
                     "by_reason": dict(Counter(r.get("reason", "") if r.get("prompted") else "heartbeat"
                                               for r in messages))},
        "telegram_inbound": {"total": len(inbound), "by_status": dict(Counter(r.get("status") for r in inbound))},
        "model_calls": {**model_calls, "total_at_least": sum(model_calls.values())},
        "daemon_cycles": len(overnight), "proactive_ticks": dict(ticks),
        "situation": {"samples": len(samples), "known_fraction": freshness},
        "owner_contacts": sum(1 for e in stops if e.kind == "owner.contact"),
        "services": supervisor,
    }


def render(report: dict[str, Any]) -> str:
    """Markdown for docs/engineering/life-layer/24h-report.md."""
    r = report
    lines = [f"# Life layer run report, {r['window']['from']} to {r['window']['to']}", "",
             "Generated by `ghost life-report` from Ghost's durable records. Live run, not a mock.", "",
             "| Metric | Value |", "|---|---|",
             f"| Daemon cycles | {r['daemon_cycles']} |",
             f"| Heartbeats | {r['heartbeats']['total']} ({r['heartbeats']['actions']}) |",
             f"| Messages to owner | {r['messages']['total']} (unprompted {r['messages']['unprompted']}, "
             f"prompted {r['messages']['prompted']}, Telegram sent {r['messages']['telegram_sent']}) |",
             f"| Messages by reason | {r['messages']['by_reason']} |",
             f"| Telegram inbound | {r['telegram_inbound']['total']} {r['telegram_inbound']['by_status']} |",
             f"| Model calls (at least) | {r['model_calls']['total_at_least']} {r['model_calls']} |",
             f"| Proactive ticks | {r['proactive_ticks']} |",
             f"| Situation samples | {r['situation']['samples']} |"]
    for name, fraction in r["situation"]["known_fraction"].items():
        lines.append(f"| Situation `{name}` known | {'n/a' if fraction is None else f'{fraction:.0%}'} |")
    services = r.get("services") or {}
    for name in ("relay", "daemon"):
        part = services.get(name) or {}
        lines.append(f"| Service {name} | alive={part.get('alive')} restarts={part.get('restarts')} |")
    lines += ["", "Model call counts are a floor: briefings make several calls per goal (one per page plus ideas)."]
    return "\n".join(lines) + "\n"
